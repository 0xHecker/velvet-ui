import { mkdir, readFile, writeFile } from "node:fs/promises";
import { DOCS } from "../src/docs/catalog.js";
import { DEMO_SOURCES } from "../src/docs/demo-sources.js";
import {
  CURRENT_DOCS_VERSION,
  getDocsVersion,
} from "../src/docs/versioning.js";

const args = process.argv.slice(2);
const check = args.includes("--check");
const force = args.includes("--force");
const version = args.find((arg) => !arg.startsWith("--")) || CURRENT_DOCS_VERSION;
const semver = /^\d+\.\d+\.\d+$/;

if (!semver.test(version)) {
  throw new Error(`Documentation version must be a full semantic version, received “${version}”.`);
}

const versionEntry = getDocsVersion(version);

if (!versionEntry) {
  throw new Error(
    `Register ${version} in src/docs/versioning.js before creating its snapshot.`
  );
}

if (force && versionEntry.status !== "current") {
  throw new Error(
    `${version} is archived. Archived documentation snapshots cannot be overwritten.`
  );
}

const examples = await Promise.all(
  DEMO_SOURCES.map(async (demo) => {
    const [component, styles] = await Promise.all([
      readFile(`src/playground/examples/${demo.file}.jsx`, "utf8"),
      readFile(`src/playground/examples/${demo.file}.css`, "utf8"),
    ]);
    return {
      id: demo.id,
      title: demo.title,
      component: component.trim(),
      styles: styles.trim(),
    };
  })
);

const serialized = JSON.stringify(
  {
    version,
    docs: DOCS,
    examples,
  },
  null,
  2
).replaceAll("</script", "<\\/script");

const output = `// Generated by scripts/snapshot-doc-version.mjs.
// Treat this file as immutable after the version is released.
const snapshot = ${serialized};

export default snapshot;
`;

const target = `src/docs/versions/${version}.generated.js`;
const existing = await readFile(target, "utf8").catch(() => null);

if (check) {
  if (existing !== output) {
    console.error(
      `${target} is out of date. Review the documentation changes, then run npm run docs:snapshot -- --force.`
    );
    process.exitCode = 1;
  }
} else {
  if (existing && !force) {
    throw new Error(
      `${target} already exists. Version snapshots are immutable; pass --force only while intentionally updating the current unreleased version.`
    );
  }
  await mkdir("src/docs/versions", { recursive: true });
  await writeFile(target, output);
  console.log(`Captured Velvet UI documentation ${version}.`);
}
